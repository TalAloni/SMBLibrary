using Microsoft.VisualStudio.TestTools.UnitTesting;
using SMBLibrary.SMB1;

namespace SMBLibrary.Tests.SMB1
{
    [TestClass]
    public class NegotiateResponseParsingTests
    {
        [TestMethod]
        public void ParseSMB1MessageWithNegotiateResponseFromWindowsNT4()
        {
            // Arrange
            byte[] responseBytes = new byte[] { 0xFF, 0x53, 0x4D, 0x42, 0x72, 0x00, 0x00, 0x00, 0x00, 0x80, 0x41, 0x48, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x11, 0x00, 0x00, 0x07, 0x32, 0x00, 0x01, 0x00, 0x04, 0x11, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFD, 0x43, 0x00, 0x00, 0xC0, 0xDB, 0x1E, 0x78, 0x2B, 0x2B, 0xDD, 0x01, 0x88, 0xFF, 0x08, 0x14, 0x00, 0x9D, 0xBE, 0xDA, 0x52, 0x8D, 0xEB, 0xEA, 0xDE, 0x4F, 0x00, 0x50, 0x00, 0x43, 0x00, 0x4F, 0x00, 0x4E, 0x00, 0x00, 0x00 };
            
            // Act
            SMB1Message smb1Message = SMB1Message.GetSMB1Message(responseBytes);
            
            // Assert
            Assert.AreEqual(1, smb1Message.Commands.Count);
            Assert.IsInstanceOfType(smb1Message.Commands[0], typeof(NegotiateResponse));
        }
    }
}
